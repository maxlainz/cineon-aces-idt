"""Single source of truth for the Cineon -> ACES2065-1 Input Transform.

Defines the Cineon decode (Kodak convention) and the Rec.709/D65 -> AP0 matrix
with CAT02 adaptation, and generates the deliverables (one CLF and one DCTL per
variant) in `transforms/`. Variants share the curve and differ only in a linear
gain that sets where 18% grey lands.

Usage:  python tools/cineon_idt.py          # regenerate the files
        python tools/cineon_idt.py --check  # fail if the files are out of date (CI)
"""
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
TRANSFORMS = ROOT / "transforms"

# --- Cineon (Kodak): 10 bits, 0.002 density per code value, negative gamma 0.6 ---
REF_WHITE = 685.0
REF_BLACK = 95.0
DENSITY_PER_CODE = 0.002
NEG_GAMMA = 0.6
CODE_MAX = 1023.0

# Same decode written as a CLF 3 Log op: lin = (10^((v - logOffset)/logSlope) - linOffset) / linSlope
LOG_SIDE_SLOPE = NEG_GAMMA / (DENSITY_PER_CODE * CODE_MAX)
LOG_SIDE_OFFSET = REF_WHITE / CODE_MAX
BLACK_OFFSET = 10.0 ** ((REF_BLACK - REF_WHITE) * DENSITY_PER_CODE / NEG_GAMMA)
LIN_SIDE_OFFSET = BLACK_OFFSET
LIN_SIDE_SLOPE = 1.0 - BLACK_OFFSET


def cineon_to_linear(v, gain=1.0):
    """Normalised Cineon code (0..1) -> linear (95 -> 0, 685 -> gain)."""
    v = np.asarray(v, dtype=np.float64)
    return gain * (10.0 ** ((v * CODE_MAX - REF_WHITE) * DENSITY_PER_CODE / NEG_GAMMA) - BLACK_OFFSET) / (1.0 - BLACK_OFFSET)


# --- Variants: name -> (gain, grey anchor description). Same curve, different exposure. ---
LAD_GREY_CODE = 445.0
VARIANTS = {
    # Kodak LAD: 18% grey card at code 445. 0.27 stops brighter than "Kodak".
    "LAD": (0.18 / float(cineon_to_linear(LAD_GREY_CODE / CODE_MAX)), "18% grey at code 445 (Kodak LAD)"),
    # Classic convention: code 685 = 1.0, so 18% grey lands at code 468.
    "Kodak": (1.0, "code 685 = 1.0 (18% grey at code 468)"),
}


def clf_path(name):
    return TRANSFORMS / (f"Cineon_{name}_to_ACES2065-1.clf" if name != "Kodak" else "Cineon_to_ACES2065-1.clf")


def dctl_path(name):
    return TRANSFORMS / "IDT" / f"IDT_Cineon_{name}.dctl"


# --- Colorimetry ---
D65 = (0.3127, 0.3290)
ACES_WHITE = (0.32168, 0.33767)
REC709 = [(0.640, 0.330), (0.300, 0.600), (0.150, 0.060)]
AP0 = [(0.7347, 0.2653), (0.0000, 1.0000), (0.0001, -0.0770)]
AP1 = [(0.713, 0.293), (0.165, 0.830), (0.128, 0.044)]
CAT02 = np.array([[0.7328, 0.4296, -0.1624],
                  [-0.7036, 1.6975, 0.0061],
                  [0.0030, 0.0136, 0.9834]])


def _xy_to_XYZ(xy):
    x, y = xy
    return np.array([x / y, 1.0, (1.0 - x - y) / y])


def rgb_to_xyz(primaries, white):
    P = np.stack([_xy_to_XYZ(p) for p in primaries], axis=1)
    return P * np.linalg.solve(P, _xy_to_XYZ(white))


def cat02(src_white, dst_white):
    s, d = CAT02 @ _xy_to_XYZ(src_white), CAT02 @ _xy_to_XYZ(dst_white)
    return np.linalg.inv(CAT02) @ np.diag(d / s) @ CAT02


def rec709_to(primaries):
    """Linear Rec.709/D65 -> ACES primaries (ACES white), CAT02 adaptation."""
    return np.linalg.inv(rgb_to_xyz(primaries, ACES_WHITE)) @ cat02(D65, ACES_WHITE) @ rgb_to_xyz(REC709, D65)


MATRIX_AP0 = rec709_to(AP0)
MATRIX_AP1 = rec709_to(AP1)


def cineon_to_aces2065(rgb, gain=1.0):
    """Full reference: Cineon RGB (0..1) -> linear ACES2065-1 (AP0)."""
    return cineon_to_linear(rgb, gain) @ MATRIX_AP0.T


# --- Deliverable generation ---
def _f(x):
    return f"{x:.10f}"


def render_clf(name):
    gain, anchor = VARIANTS[name]
    rows = "\n".join("                " + " ".join(_f(v) for v in r) for r in MATRIX_AP0)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by tools/cineon_idt.py: do not edit by hand. -->
<ProcessList compCLFversion="3" id="urn:maxlainz:cineon-aces-idt:{clf_path(name).stem}:v1" name="Cineon ({name}) to ACES2065-1">
    <Description>Input Transform: Cineon scan (printing density, Kodak convention black 95, 0.002 D/code value, negative gamma 0.6, {anchor}) to ACES2065-1. Assumed Rec.709/D65 primaries, CAT02 adaptation to the ACES white.</Description>
    <InputDescriptor>Cineon 10-bit log, normalised 0..1 (code/1023)</InputDescriptor>
    <OutputDescriptor>ACES2065-1 (AP0, linear)</OutputDescriptor>
    <Log inBitDepth="32f" outBitDepth="32f" style="logToLin" name="Cineon decode">
        <Description>lin = (10^((v - logSideOffset)/logSideSlope) - linSideOffset) / linSideSlope</Description>
        <LogParams base="10" logSideSlope="{_f(LOG_SIDE_SLOPE)}" logSideOffset="{_f(LOG_SIDE_OFFSET)}" linSideSlope="{_f(LIN_SIDE_SLOPE / gain)}" linSideOffset="{_f(LIN_SIDE_OFFSET)}"/>
    </Log>
    <Matrix inBitDepth="32f" outBitDepth="32f" name="Rec.709 D65 to AP0 (CAT02)">
        <Array dim="3 3">
{rows}
        </Array>
    </Matrix>
</ProcessList>
"""


def render_dctl(name):
    gain, anchor = VARIANTS[name]
    m = MATRIX_AP0
    lines = "\n".join(
        f"    const float {c} = {_f(m[i,0])}f * r + {_f(m[i,1])}f * g + {_f(m[i,2])}f * b;"
        for i, c in enumerate(("ra", "ga", "ba")))
    return f"""DEFINE_ACES_PARAM(IS_PARAMETRIC_ACES_TRANSFORM: 0)

// GENERATED by tools/cineon_idt.py: do not edit by hand.
//
//-------------  Cineon ({name}) IDT  -------------//
//
// Input:  Cineon 10-bit log (printing density), normalised 0..1.
//         Kodak convention: black 95, 0.002 D/code value, negative gamma 0.6.
//         Exposure anchor: {anchor}.
// Output: ACES2065-1 (AP0, linear).
// Assumed Rec.709/D65 primaries, CAT02 chromatic adaptation to the ACES white.

__DEVICE__ inline float cineonDecode(float v)
{{
    const float logSideSlope  = {_f(LOG_SIDE_SLOPE)}f;
    const float logSideOffset = {_f(LOG_SIDE_OFFSET)}f;
    const float linSideSlope  = {_f(LIN_SIDE_SLOPE / gain)}f;
    const float linSideOffset = {_f(LIN_SIDE_OFFSET)}f;
    return (_powf(10.0f, (v - logSideOffset) / logSideSlope) - linSideOffset) / linSideSlope;
}}

__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)
{{
    const float r = cineonDecode(p_R);
    const float g = cineonDecode(p_G);
    const float b = cineonDecode(p_B);

    // Rec.709 D65 -> AP0 (CAT02)
{lines}

    return make_float3(ra, ga, ba);
}}
"""


def main(argv):
    outputs = {}
    for name in VARIANTS:
        outputs[clf_path(name)] = render_clf(name)
        outputs[dctl_path(name)] = render_dctl(name)
    if "--check" in argv:
        stale = [p.relative_to(ROOT) for p, t in outputs.items() if not p.exists() or p.read_text() != t]
        if stale:
            print("Out-of-date files (run tools/cineon_idt.py):", *stale)
            return 1
        print("Files up to date.")
        return 0
    for p, t in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t)
        print("wrote", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
